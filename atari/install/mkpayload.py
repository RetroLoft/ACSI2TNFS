#!/usr/bin/env python3
"""payload.c for STINGINS.TOS: the files it installs, as C arrays.
usage: mkpayload.py OUT.c  (run in atari/install)"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))

# (folder on the Atari, file name, source)
FILES = [
    ("AUTO",        "STING.PRG",    "sting/STING.PRG"),
    ("STING",       "ACSI_NET.STX", "../sting/ACSI_NET.STX"),
    ("STING",       "TCP.STX",      "sting/TCP.STX"),
    ("STING",       "UDP.STX",      "sting/UDP.STX"),
    ("STING",       "RESOLVE.STX",  "sting/RESOLVE.STX"),
    ("STING\\TOOLS", "PING.PRG",    "sting/PING.PRG"),
    ("STING\\TOOLS", "PING.RSC",    "sting/PING.RSC"),
]
TEMPLATE = "sting/DEFAULT.CFG"


def array(f, name, data):
    f.write(f"static const unsigned char {name}[{max(len(data), 1)}] = {{\n")
    for i in range(0, len(data), 24):
        f.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("};\n")


def main():
    out = sys.argv[1]
    with open(out, "w") as f:
        f.write("/* generated by mkpayload.py - do not edit */\n")
        f.write("typedef struct { const char *dir; const char *name; const unsigned char *data; long size; } PFILE;\n\n")
        sizes = []
        for i, (_, _, src) in enumerate(FILES):
            data = open(os.path.join(HERE, src), "rb").read()
            sizes.append(len(data))
            array(f, f"f{i}", data)
        tmpl = open(os.path.join(HERE, TEMPLATE), "rb").read()
        f.write("\nconst unsigned char cfg_default[] = {\n")
        for i in range(0, len(tmpl), 24):
            f.write("  " + ",".join(str(b) for b in tmpl[i:i + 24]) + ",\n")
        f.write("};\n")
        f.write(f"const long cfg_default_size = {len(tmpl)};\n\n")
        f.write("const PFILE payload[] = {\n")
        for i, (d, n, _) in enumerate(FILES):
            cdir = d.replace("\\", "\\\\")
            f.write(f'  {{ "{cdir}", "{n}", f{i}, {sizes[i]} }},\n')
        f.write("  { 0, 0, 0, 0 }\n};\n")
    print(f"  payload: {len(FILES)} files, {sum(sizes)} bytes + DEFAULT.CFG {len(tmpl)}")


if __name__ == "__main__":
    main()
